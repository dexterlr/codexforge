export function buildAiProviderProfile(
  profile: Partial<AiProviderProfile> & Pick<AiProviderProfile, "id" | "label" | "kind">
): AiProviderProfile {
  return {
    connectionMode: "planned",
    secretStrategy: "not-configured",
    privacyPosture: "unknown",
    latencyExpectation: "variable",
    reliabilityExpectation: "variable",
    supportsStreaming: false,
    supportsToolUse: false,
    supportsVision: false,
    supportsCode: false,
    supportsLongContext: false,
    supportsLocalOffline: false,
    notes: [],
    status: "planned",
    ...profile,
  };
}

