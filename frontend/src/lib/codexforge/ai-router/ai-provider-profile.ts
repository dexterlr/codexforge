export function isAiProviderConfigured(profile: AiProviderProfile): boolean {
  return profile.status === "configured";
}

export function summarizeAiProviderProfile(profile: AiProviderProfile): string {
  return `${profile.label}: ${profile.status}, ${profile.connectionMode}, ${profile.secretStrategy}, privacy ${profile.privacyPosture}.`;
}
